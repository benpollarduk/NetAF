namespace NetAF.Rendering
{
    /// <summary>
    /// Enumeration of key placements.
    /// </summary>
    public enum KeyPlacement
    {
        /// <summary>
        /// Place the key to the right of the map.
        /// </summary>
        Right = 0,
        /// <summary>
        /// Place the key to the left of the map.
        /// </summary>
        Left,
        /// <summary>
        /// Place the key above the map.
        /// </summary>
        Above,
        /// <summary>
        /// Place the key below the map.
        /// </summary>
        Below
    }
}
